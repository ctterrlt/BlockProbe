_current: str = DEFAULT_LANGUAGE


def is_supported(code: str) -> bool:
    return str(code or "").lower() in LANGUAGES


def set_language(code: str) -> str:
    """Set the process-wide language; raises ``ValueError`` when unsupported."""
    normalized = str(code or "").strip().lower()
    if normalized not in LANGUAGES:
        raise ValueError(
            f"Unsupported language {code!r}. Supported: {', '.join(LANGUAGES)}."
        )
    global _current
    _current = normalized
    return _current


def get_language() -> str:
    return _current


def available_languages() -> dict[str, str]:
    """Return ``code -> native name`` in the documented display order."""
    return dict(LANGUAGES)


def t(message: str, **values: object) -> str:
    """Translate ``message`` and fill ``{placeholders}`` when provided.

    Unknown strings fall back to the English original; formatting errors fall
    back to the untranslated string so a bad placeholder can never crash the UI.
    """
    catalog = _translations.get(_current, {})
    text = catalog.get(message, message)
    if not values:
        return text
    try:
        return text.format(**values)
    except (KeyError, IndexError, ValueError):
        return text
